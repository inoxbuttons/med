-- Новые врачи: специальность берём из _specs (с направлением), чтобы не зацепить одноимённые из сети 1
INSERT INTO doctors (name, speciality_id)
SELECT DISTINCT ON (dd.fio) dd.fio, s.id
FROM _docs dd
JOIN _specs sp ON sp.name = dd.spec
JOIN med_fields mf ON mf.name = sp.med_field
JOIN specialities s ON s.name = sp.name AND s.med_field_id = mf.id
WHERE dd.fio NOT IN (SELECT name FROM _net_doctors)
ORDER BY dd.fio, s.id;

-- Обновляем список врачей сети: новые врачи пока без мест приёма, ищем их по ФИО среди только что созданных
INSERT INTO _net_doctors
SELECT d.id, d.name FROM doctors d
WHERE d.name IN (SELECT fio FROM _docs)
  AND d.name NOT IN (SELECT name FROM _net_doctors)
  AND NOT EXISTS (SELECT 1 FROM doctor_locations dl WHERE dl.doctor_id = d.id);

INSERT INTO doctor_locations (doctor_id, clinic_id, price)
SELECT nd.id, c.id, dd.price
FROM _docs dd
JOIN _net_doctors nd ON nd.name = dd.fio
JOIN _net_clinics c ON c.name = dd.clinic
WHERE NOT EXISTS (SELECT 1 FROM doctor_locations dl WHERE dl.doctor_id = nd.id AND dl.clinic_id = c.id);

-- 4. Расписание ---------------------------------------------------------------
-- Пересоздаём у врачей сети, у которых набор клиник в расписании не совпадает с местами приёма
CREATE TEMP TABLE _reschedule ON COMMIT DROP AS
SELECT nd.id AS doctor_id
FROM _net_doctors nd
WHERE ARRAY(SELECT DISTINCT dl.clinic_id FROM doctor_locations dl WHERE dl.doctor_id = nd.id ORDER BY 1)
   IS DISTINCT FROM
      ARRAY(SELECT DISTINCT w.clinic_id FROM doctor_working_hours w WHERE w.doctor_id = nd.id ORDER BY 1);

DELETE FROM doctor_working_hours WHERE doctor_id IN (SELECT doctor_id FROM _reschedule);

WITH locs AS (
  SELECT dl.doctor_id, dl.clinic_id,
         ROW_NUMBER() OVER (PARTITION BY dl.doctor_id ORDER BY dl.clinic_id) AS rn,
         COUNT(*)     OVER (PARTITION BY dl.doctor_id)                       AS cnt
  FROM doctor_locations dl
